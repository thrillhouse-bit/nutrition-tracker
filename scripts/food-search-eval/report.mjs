// Emits the before/after comparison table for docs/food-search-eval.md from
// the two summary artifacts, so the published numbers are generated from the
// measurements rather than transcribed by hand.
//
//   node scripts/food-search-eval/analyze.mjs        # writes summary.json (after)
//   node scripts/food-search-eval/report.mjs         # prints the markdown
//
// summary.before-fix.json is produced by running the same analyze.mjs over a
// corpus run made from a worktree at this branch's base commit — same items,
// same providers, same matcher, the pre-overhaul pipeline.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const after = JSON.parse(fs.readFileSync(path.join(__dirname, 'summary.json'), 'utf8'))
const before = JSON.parse(fs.readFileSync(path.join(__dirname, 'summary.before-fix.json'), 'utf8'))

const n = (v, suffix = '') => (v == null ? '—' : `${v}${suffix}`)
const delta = (b, a, suffix = '%') => {
  if (b == null || a == null) return '—'
  const d = +(a - b).toFixed(1)
  return `${d > 0 ? '+' : ''}${d}${suffix}`
}

function block(title, bKey, aKey) {
  const rows = ['generic', 'branded', 'all']
  const out = [`### ${title}`, '', '| | top-1 | top-3 | top-5 | MRR | zero-result | p50 | p95 |', '|---|---|---|---|---|---|---|---|']
  for (const kind of rows) {
    const b = bKey[kind]
    const a = aKey[kind]
    if (!b || !a) continue
    out.push(`| **${kind}** before | ${n(b.top1Pct, '%')} | ${n(b.top3Pct, '%')} | ${n(b.top5Pct, '%')} | ${b.mrr} | ${n(b.zeroResultPct, '%')} | ${n(b.latencyP50Ms, 'ms')} | ${n(b.latencyP95Ms, 'ms')} |`)
    out.push(`| **${kind}** after | **${n(a.top1Pct, '%')}** | ${n(a.top3Pct, '%')} | ${n(a.top5Pct, '%')} | ${a.mrr} | ${n(a.zeroResultPct, '%')} | ${n(a.latencyP50Ms, 'ms')} | ${n(a.latencyP95Ms, 'ms')} |`)
    out.push(`| ${kind} change | ${delta(b.top1Pct, a.top1Pct)} | ${delta(b.top3Pct, a.top3Pct)} | ${delta(b.top5Pct, a.top5Pct)} | ${delta(b.mrr, a.mrr, '')} | ${delta(b.zeroResultPct, a.zeroResultPct)} | ${delta(b.latencyP50Ms, a.latencyP50Ms, 'ms')} | ${delta(b.latencyP95Ms, a.latencyP95Ms, 'ms')} |`)
  }
  out.push('')
  return out.join('\n')
}

console.log(`<!-- generated by scripts/food-search-eval/report.mjs -->`)
console.log(`Corpus: ${after.distinctItems} items (${after.corpusSplit.generic} generic / ${after.corpusSplit.branded} branded), ${after.totalProbes} probes after, ${before.totalProbes} before.`)
console.log(`${after.note}\n`)
console.log(block('Complete query', before.completeQuery, after.completeQuery))
console.log(`Targets in NEITHER database — no ranking can move these: before ${before.targetsNotInEitherDatabase.branded} branded / ${before.targetsNotInEitherDatabase.generic} generic; after ${after.targetsNotInEitherDatabase.branded} branded / ${after.targetsNotInEitherDatabase.generic} generic.\n`)
console.log(block('Complete query, excluding targets neither database carries', before.completeQueryRetrievableOnly, after.completeQueryRetrievableOnly))
for (const len of [2, 3, 4, 5]) console.log(block(`Prefix of ${len} characters`, before.byPrefixLength[len], after.byPrefixLength[len]))

console.log('### Time to first useful result (target reaches the top 5)\n')
console.log('| | items reaching top 5 | characters typed p50 | p95 | search p50 | p95 |')
console.log('|---|---|---|---|---|---|')
for (const kind of ['generic', 'branded', 'all']) {
  const b = before.timeToFirstUsefulResult[kind]
  const a = after.timeToFirstUsefulResult[kind]
  console.log(`| **${kind}** before | ${b.itemsReachingTop5} | ${b.charactersTypedP50} | ${b.charactersTypedP95} | ${b.searchLatencyP50Ms}ms | ${b.searchLatencyP95Ms}ms |`)
  console.log(`| **${kind}** after | **${a.itemsReachingTop5}** | ${a.charactersTypedP50} | ${a.charactersTypedP95} | ${a.searchLatencyP50Ms}ms | ${a.searchLatencyP95Ms}ms |`)
}
console.log(`\nItems never reaching the top 5 at any probe: **${before.itemsNeverReachingTop5} before -> ${after.itemsNeverReachingTop5} after.**`)
